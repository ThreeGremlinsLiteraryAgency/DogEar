begin;

create table if not exists public.book_reviews (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  book_id bigint not null references public.books(id) on delete cascade,
  rating smallint not null check (rating between 1 and 5),
  review_text text check (review_text is null or char_length(review_text) <= 4000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, book_id)
);

create index if not exists book_reviews_book_id_idx
  on public.book_reviews(book_id);

create index if not exists book_reviews_user_id_idx
  on public.book_reviews(user_id);

alter table public.book_reviews enable row level security;

drop policy if exists "Anyone can read book reviews" on public.book_reviews;
create policy "Anyone can read book reviews"
  on public.book_reviews
  for select
  to anon, authenticated
  using (true);

drop policy if exists "Users create own book reviews" on public.book_reviews;
create policy "Users create own book reviews"
  on public.book_reviews
  for insert
  to authenticated
  with check ((select auth.uid()) = user_id);

drop policy if exists "Users update own book reviews" on public.book_reviews;
create policy "Users update own book reviews"
  on public.book_reviews
  for update
  to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

drop policy if exists "Users delete own book reviews" on public.book_reviews;
create policy "Users delete own book reviews"
  on public.book_reviews
  for delete
  to authenticated
  using ((select auth.uid()) = user_id);

grant select on public.book_reviews to anon, authenticated;
grant insert, update, delete on public.book_reviews to authenticated;
grant usage, select on sequence public.book_reviews_id_seq to authenticated;

drop trigger if exists set_book_reviews_updated_at on public.book_reviews;
create trigger set_book_reviews_updated_at
before update on public.book_reviews
for each row execute function public.set_updated_at();

drop policy if exists "Users delete own books" on public.user_books;
create policy "Users delete own books"
  on public.user_books
  for delete
  to authenticated
  using ((select auth.uid()) = user_id);

grant delete on public.user_books to authenticated;

