  affiliate_disclosure text not null default 'Paper Gremlin may earn a commission from qualifying purchases made through affiliate links.',
  premium_price numeric(10,2) not null default 10 check (premium_price >= 0),
  premium_tokens integer not null default 1000 check (premium_tokens >= 0),
